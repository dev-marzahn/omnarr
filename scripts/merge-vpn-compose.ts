// Writes compose.vpn.merged.yml: compose.yml with compose.vpn.yml merged over
// it, the VPN layout in one file for a front end that deploys a single compose
// file and ignores COMPOSE_FILE (Coolify). The two source files stay the ones
// to edit; `bun run ready` fails while the merged file is out of date, and the
// release workflow runs this after it pins compose.yml.
//
//   node scripts/merge-vpn-compose.ts
//
// The merge is Compose's for the shapes compose.vpn.yml uses: mappings merge by
// key, a scalar or a new key replaces, and `!reset` removes the key. A sequence
// in both files fails, since Compose merges some of those by key; comments are
// kept.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { isMap, isScalar, isSeq, type Node, parseDocument, Scalar, type YAMLMap } from 'yaml';

export const MERGED_FILE = 'compose.vpn.merged.yml';

const HEADER = ` omnarr, the VPN layout in one file: compose.yml with compose.vpn.yml merged
 over it, for a front end that deploys one compose file, such as Coolify.
 Generated by \`node scripts/merge-vpn-compose.ts\`; edit those two files instead.
 Needs Docker Compose 2.24 or later and /dev/net/tun on the host. Gluetun
 carries qBittorrent's traffic, and qBittorrent publishes no port. To recreate
 gluetun, recreate qBittorrent with it, or qBittorrent keeps a dead network.

 These pins are the release's manifest: every image by tag and digest.`;

const isReset = (node: unknown) => (isScalar(node) || isSeq(node) || isMap(node)) && (node as Node).tag === '!reset';

function mergeMap(base: YAMLMap, override: YAMLMap, path: string): void {
  for (const pair of override.items) {
    const key = isScalar(pair.key) ? String(pair.key.value) : String(pair.key);
    const at = path ? `${path}.${key}` : key;
    if (isReset(pair.value)) {
      base.delete(key);
      continue;
    }
    const current = base.get(key, true);
    if (isMap(current) && isMap(pair.value)) mergeMap(current, pair.value, at);
    else if (isSeq(current) && isSeq(pair.value)) throw new Error(`${at}: a sequence in both files; Compose merges some by key, so merge it by hand`);
    else if (current === undefined) base.items.push(pair);
    else base.set(key, pair.value);
  }
}

/** compose.yml with compose.vpn.yml merged over it, as one file's text. */
export function mergeVpnCompose(base: string, vpn: string): string {
  const options = { customTags: [{ tag: '!reset', resolve: (value: string) => new Scalar(value) }] };
  const merged = parseDocument(base, options);
  const override = parseDocument(vpn, options);
  for (const doc of [merged, override]) if (doc.errors.length > 0) throw doc.errors[0]!;
  if (!isMap(merged.contents) || !isMap(override.contents)) throw new Error('a compose file is not a mapping');
  mergeMap(merged.contents, override.contents, '');
  // compose.yml's own header is the direct layout's.
  merged.commentBefore = HEADER;
  merged.contents.commentBefore = null;
  const first = merged.contents.items[0]?.key;
  if (isScalar(first)) first.commentBefore = null;
  return merged.toString({ lineWidth: 0, flowCollectionPadding: false });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(fileURLToPath(import.meta.url), '../..');
  const read = (file: string) => readFileSync(join(root, file), 'utf8');
  writeFileSync(join(root, MERGED_FILE), mergeVpnCompose(read('compose.yml'), read('compose.vpn.yml')));
  console.log(`Wrote ${MERGED_FILE}.`);
}
