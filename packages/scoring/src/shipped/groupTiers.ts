/**
 * One family's lists, best tier first: each name once (first spelling kept,
 * case ignored), in the best tier that lists it, and not in any tier when the
 * low-quality list has it.
 */
function family<T extends string>(lowQuality: readonly string[], tiers: [T, readonly string[]][]): Record<T, string[]> {
  const seen = new Set(lowQuality.map((name) => name.toLowerCase()));
  const result = {} as Record<T, string[]>;
  for (const [id, names] of tiers) {
    result[id] = [];
    for (const name of names) {
      if (seen.has(name.toLowerCase())) continue;
      seen.add(name.toLowerCase());
      result[id].push(name);
    }
  }
  return result;
}

